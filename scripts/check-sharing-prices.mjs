import assert from 'node:assert/strict';
import { buildSharePayload, GAME_URL, shareCaption, SHARE_SIZE, shareStats } from '../src/share-payload.mjs';
import { productPrices, productPriceMarkup } from '../src/product-pricing.mjs';
assert.deepEqual(shareStats(2,24,19),{score:2,record:24});
assert.deepEqual(shareStats(30,24),{score:30,record:30});
assert.deepEqual(shareStats(0,0,undefined),{score:0,record:0});
assert.deepEqual(SHARE_SIZE,{width:1080,height:1920});
assert.ok(shareCaption(2).includes('۲ امتیاز'));
assert.ok(shareCaption(0).includes('۰ امتیاز'));
assert.equal(shareCaption(2).split(GAME_URL).length,2);
const image=new Blob(['png'],{type:'image/png'}), payload=buildSharePayload(image,'رکورد من: ۱۲');
assert.equal(payload.url,GAME_URL);assert.ok(payload.text.includes(GAME_URL));assert.ok(payload.title.includes('دیجی‌کالا'));assert.equal(payload.files[0].type,'image/png');assert.equal(payload.files[0].size,image.size);
assert.equal(buildSharePayload(image,GAME_URL).text.split(GAME_URL).length,2,'The caption contains the URL exactly once');
assert.deepEqual(productPrices({originalPrice:1000,salePrice:800,deal:{discountPercent:20}}),{original:1000,current:800,discounted:true});
assert.equal(productPrices({gamePrice:1000,deal:{discountPercent:20}}).current,800);
assert.ok(!productPriceMarkup({originalPrice:1000,salePrice:1000}).includes('<del'));
assert.ok(productPriceMarkup({originalPrice:1000,salePrice:800}).includes('<del'));
assert.ok(!productPriceMarkup({}).includes('تومان'));
assert.equal(productPrices({originalPrice:1000,salePrice:900,deal:{discountPercent:20}}).current,900,'The authoritative sale price wins over a percentage estimate');
globalThis.window={addEventListener(){}};
const host=await import('../src/host.js');let packet;host.configureHost({share:async p=>{packet=p;return 'sent';}});
assert.equal(await host.share(image,'رکورد من',GAME_URL),'sent');assert.equal(packet.blob,image);assert.equal(packet.url,GAME_URL);assert.ok(packet.text.includes(GAME_URL),'The host receives the URL in the caption as well as a separate field');
console.log('Sharing: PNG + playable URL + branded caption; prices: original, sale, no-discount, authoritative sale and missing price passed.');
